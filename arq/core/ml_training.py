"""Training and calibration utilities for the optional ARQ ML detector."""

from __future__ import annotations

import json
import math
import os
import tempfile
from pathlib import Path
from typing import Any

import joblib
import numpy as np
from sklearn.ensemble import IsolationForest
from sklearn.model_selection import train_test_split

from arq.core.ml_pipeline import FEATURE_NAMES


def load_jsonl(path: str | Path) -> np.ndarray:
    """Load JSONL telemetry records containing the seven ARQ feature fields."""
    rows = []
    required = set(FEATURE_NAMES)

    with open(path, "r", encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, start=1):
            if not line.strip():
                continue

            try:
                record = json.loads(line)
                row = [float(record[name]) for name in FEATURE_NAMES]
            except (json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
                raise ValueError(
                    f"Invalid telemetry record on line {line_number}: {exc}"
                ) from exc

            if not all(math.isfinite(value) for value in row):
                raise ValueError(
                    f"Non-finite telemetry value on line {line_number}."
                )
            if any(value < 0 for value in row):
                raise ValueError(
                    f"Negative resource value on line {line_number}."
                )

            rows.append(row)

    if len(rows) < 20:
        raise ValueError(
            "At least 20 valid records are required for training and calibration."
        )

    data = np.asarray(rows, dtype=np.float64)
    if not np.any(np.ptp(data, axis=0) > 0):
        raise ValueError("Training data has no variation across any feature.")

    return data


def train_isolation_forest(
    data_path: str | Path,
    output_dir: str | Path = "models/arq",
    contamination: float = 0.05,
    random_state: int = 42,
) -> dict[str, Any]:
    """Train on one partition and calibrate a threshold on held-out normal data.

    Input data must represent normal process behavior. The held-out quantile
    controls the expected calibration exceedance rate; it is not a measured
    false-positive rate on future workloads.
    """
    if not 0 < contamination < 0.5:
        raise ValueError("contamination must be between 0 and 0.5.")

    data = load_jsonl(data_path)
    training, calibration = train_test_split(
        data, test_size=0.25, random_state=random_state
    )

    model = IsolationForest(
        n_estimators=200,
        contamination=contamination,
        random_state=random_state,
        n_jobs=-1,
    )
    model.fit(training)

    # decision_function is higher for normal observations. Negate it so
    # higher anomaly scores indicate more unusual observations.
    calibration_scores = -model.decision_function(calibration)
    threshold = float(np.quantile(calibration_scores, 1.0 - contamination))

    destination = Path(output_dir)
    destination.mkdir(parents=True, exist_ok=True)
    artifact = {
        "model": model,
        "feature_names": list(FEATURE_NAMES),
        "calibration_threshold": threshold,
        "contamination": contamination,
        "training_rows": int(len(training)),
        "calibration_rows": int(len(calibration)),
        "random_state": random_state,
    }

    # Write atomically so an interrupted save won't leave a partial artifact.
    fd, temporary_path = tempfile.mkstemp(
        prefix=".arq-model-", suffix=".joblib", dir=destination
    )
    os.close(fd)
    try:
        joblib.dump(artifact, temporary_path)
        os.replace(temporary_path, destination / "isolation_forest.joblib")
    finally:
        if os.path.exists(temporary_path):
            os.unlink(temporary_path)

    return {
        "model_path": str(destination / "isolation_forest.joblib"),
        "training_rows": int(len(training)),
        "calibration_rows": int(len(calibration)),
        "calibration_threshold": threshold,
    }


def load_isolation_forest(path: str | Path) -> dict[str, Any]:
    """Load an artifact generated by this module.

    Only load model artifacts from trusted sources: joblib uses pickle internally.
    """
    artifact = joblib.load(path)
    if not isinstance(artifact, dict):
        raise ValueError("Invalid ARQ model artifact.")
    if artifact.get("feature_names") != list(FEATURE_NAMES):
        raise ValueError("Model feature schema does not match this ARQ version.")
    if "model" not in artifact or "calibration_threshold" not in artifact:
        raise ValueError("Model artifact is missing required fields.")
    return artifact
